// ── Paths inside the chat folder (relative, `/`-separated, '' = the folder) ──

export function isMarkdownPath(path: string): boolean {
  return /\.md$/i.test(path);
}

export function isDocxPath(path: string): boolean {
  return /\.docx$/i.test(path);
}

/** A file the document browser offers: Markdown or Word. */
export function isOpenableDoc(name: string): boolean {
  return isMarkdownPath(name) || isDocxPath(name);
}

export function joinRel(dir: string, name: string): string {
  return dir === '' ? name : `${dir}/${name}`;
}

/** The directory above `path`, '' for the chat folder itself, null above that. */
export function parentRel(path: string): string | null {
  if (path === '') return null;
  const i = path.lastIndexOf('/');
  return i === -1 ? '' : path.slice(0, i);
}

export function baseName(path: string): string {
  return path.slice(path.lastIndexOf('/') + 1);
}

/** One entry of a chat-folder listing. */
export interface FolderEntry {
  name: string;
  type: 'file' | 'dir';
}

/** Folders first, then `.md`/`.docx` files, each A to Z; every other file is left out. */
export function documentEntries(entries: readonly FolderEntry[]): FolderEntry[] {
  const byName = (a: FolderEntry, b: FolderEntry): number => a.name.localeCompare(b.name);
  const dirs = entries.filter((e) => e.type === 'dir').sort(byName);
  const docs = entries.filter((e) => e.type === 'file' && isOpenableDoc(e.name)).sort(byName);
  return [...dirs, ...docs];
}

// Typed routes are generated by the dev server from app/, so a route added
// since the last `expo start` is not in the generated types yet: these build
// the href as the object form and assert it, as lib/newPad.ts does.
export function docRoute(chatId: string, path: string): Href {
  return { pathname: '/chats/[chatId]/doc', params: { chatId, path } } as unknown as Href;
}

export function docsRoute(chatId: string, path?: string): Href {
  return {
    pathname: '/chats/[chatId]/docs',
    params: path === undefined || path === '' ? { chatId } : { chatId, path },
  } as unknown as Href;
}

/**
 * Save-conflict check (web: detectSaveConflict, Zed's model). `baseline` is
 * what the draft was started against, `onDisk` a fresh read, `draft` what Save
 * would write. A conflict is the disk having moved to bytes that are neither.
 */
export function detectSaveConflict(params: {
  baseline: string;
  onDisk: string;
  draft: string;
}): boolean {
  const { baseline, onDisk, draft } = params;
  if (onDisk === baseline) return false;
  if (onDisk === draft) return false;
  return true;
}
