// Document editor — the pure half (spec/14 § Document editor, spec/15 §
// Document editor). The phone twin of packages/web/src/lib/quoteSelection.ts
// and the panels' ordering rules: selection quoting into the composer draft,
// pending-before-resolved lists, the chat-folder path helpers, and the
// save-conflict check the plain editor uses.

import { joinQuotes, splitQuotes } from './composerQuotes';
import type { DocThread, DocView } from '@patch/wire';
import type { Href } from 'expo-router';

/** A text selection as TextInput reports it. */
export interface TextSelection {
  start: number;
  end: number;
}

/** The selected text, or '' when the selection is collapsed. */
export function selectedText(text: string, sel: TextSelection): string {
  const a = Math.min(sel.start, sel.end);
  const b = Math.max(sel.start, sel.end);
  return text.slice(a, b);
}

/**
 * `selected` added to the stack of quotes at the head of `existingDraft`
 * (web: withQuotedSelection).
 */
export function withQuotedSelection(existingDraft: string, selected: string): string {
  const { quotes, body } = splitQuotes(existingDraft);
  return joinQuotes([...quotes, selected], body);
}

/** Pending suggestions first, then the accepted/rejected ones, each in made-order. */
export function orderSuggestions(view: DocView): {
  pending: DocView['suggestions'];
  resolved: DocView['suggestions'];
  all: DocView['suggestions'];
} {
  const pending = view.suggestions.filter((s) => s.status === 'pending');
  const resolved = view.suggestions.filter((s) => s.status !== 'pending');
  return { pending, resolved, all: [...pending, ...resolved] };
}

/** Open threads first; a resolved one sorts after them. */
export function orderThreads(view: DocView): {
  open: DocThread[];
  resolved: DocThread[];
  all: DocThread[];
} {
  const open = view.threads.filter((t) => !t.resolved);
  const resolved = view.threads.filter((t) => t.resolved);
  return { open, resolved, all: [...open, ...resolved] };
}

/** Versions newest first (the view carries them oldest first). */
export function versionsNewestFirst(view: DocView): DocView['versions'] {
  return [...view.versions].reverse();
}

